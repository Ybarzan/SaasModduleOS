-- Outbox des événements d'expédition envoyés à compliance-engine. Écrits dans la
-- même transaction que le changement d'expédition (jamais d'événement fantôme sur
-- rollback, jamais d'événement perdu si compliance-engine est indisponible), puis
-- envoyés après commit par OutboundEventDispatcher avec nouvelles tentatives.
CREATE TABLE outbound_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id UUID NOT NULL,
    company_id BIGINT NOT NULL,
    event_type VARCHAR(50) NOT NULL,
    payload TEXT NOT NULL,
    status VARCHAR(20) NOT NULL,
    attempts INTEGER NOT NULL DEFAULT 0,
    next_attempt_at TIMESTAMP(6) NOT NULL,
    last_error VARCHAR(1000),
    created_at TIMESTAMP(6) NOT NULL,
    sent_at TIMESTAMP(6),
    CONSTRAINT fk_outbound_event_company FOREIGN KEY (company_id) REFERENCES company ON DELETE CASCADE,
    CONSTRAINT uk_outbound_event_event_id UNIQUE (event_id),
    CONSTRAINT outbound_event_status_check CHECK (status IN ('PENDING','SENT','FAILED'))
);
CREATE INDEX idx_outbound_event_due ON outbound_event (status, next_attempt_at);
CREATE INDEX idx_outbound_event_company ON outbound_event (company_id, status, id);
