-- Une clé machine-à-machine par hub consommateur (compliance-engine, Logistix,
-- Finance, portail Praxio) au lieu d'une clé unique partagée : droits limités à ce
-- dont chaque hub a besoin, rotation et révocation indépendantes.
CREATE TABLE integration_api_key (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL,
    consumer VARCHAR(32) NOT NULL,
    key_hash VARCHAR(64) NOT NULL,
    key_hint VARCHAR(8),
    created_at TIMESTAMP(6) NOT NULL,
    last_used_at TIMESTAMP(6),
    CONSTRAINT fk_integration_key_company FOREIGN KEY (company_id) REFERENCES company ON DELETE CASCADE,
    CONSTRAINT uk_integration_key_hash UNIQUE (key_hash),
    CONSTRAINT uk_integration_key_consumer UNIQUE (company_id, consumer),
    CONSTRAINT integration_api_key_consumer_check
        CHECK (consumer IN ('LEGACY','COMPLIANCE_ENGINE','LOGISTIX','FINANCE','PORTAL'))
);

-- La clé partagée existante devient la clé « historique » : les hubs qui l'utilisent
-- continuent de fonctionner jusqu'à ce que l'admin la révoque.
INSERT INTO integration_api_key (company_id, consumer, key_hash, created_at)
SELECT id, 'LEGACY', internal_integration_api_key, CURRENT_TIMESTAMP
FROM company
WHERE internal_integration_api_key IS NOT NULL;

ALTER TABLE company DROP COLUMN internal_integration_api_key;
