-- Activité « Transport médical » : comptage des produits par catégorie à chaque
-- passage, journal de garde chaîné (infalsifiable) et non-conformités.

-- Délai maximal entre la prise en charge d'un produit et sa remise au laboratoire.
ALTER TABLE company ADD COLUMN medical_max_transit_minutes INTEGER NOT NULL DEFAULT 240;

-- Quantités collectées / remises par catégorie de produit (sang, PCR, urines…).
CREATE TABLE tour_stop_product (
    tour_stop_id BIGINT NOT NULL REFERENCES tour_stop(id) ON DELETE CASCADE,
    category VARCHAR(32) NOT NULL CHECK (category IN ('SANG','PCR','URINE','AUTRE')),
    quantity INTEGER NOT NULL CHECK (quantity >= 0),
    PRIMARY KEY (tour_stop_id, category)
);

-- Journal de garde : ajout seul. Chaque événement porte l'empreinte SHA-256 du
-- précédent (par société) : toute modification ou suppression a posteriori
-- casse la chaîne et est détectée par la vérification d'intégrité.
CREATE TABLE custody_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES company(id),
    sequence_no BIGINT NOT NULL,
    event_type VARCHAR(32) NOT NULL,
    tour_id BIGINT,
    tour_stop_id BIGINT,
    tour_name VARCHAR(255),
    site_name VARCHAR(255),
    site_kind VARCHAR(32),
    occurred_at TIMESTAMP(6) NOT NULL,
    recorded_at TIMESTAMP(6) NOT NULL,
    actor VARCHAR(255) NOT NULL,
    products VARCHAR(255),
    total_quantity INTEGER,
    temperature_celsius FLOAT(53),
    signed_by VARCHAR(255),
    latitude FLOAT(53),
    longitude FLOAT(53),
    details VARCHAR(1000),
    previous_hash VARCHAR(64) NOT NULL,
    hash VARCHAR(64) NOT NULL,
    CONSTRAINT uk_custody_company_seq UNIQUE (company_id, sequence_no)
);
CREATE INDEX idx_custody_company_occurred ON custody_event(company_id, occurred_at);
CREATE INDEX idx_custody_tour ON custody_event(tour_id);

CREATE TABLE non_conformity (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES company(id),
    tour_id BIGINT REFERENCES tour(id) ON DELETE SET NULL,
    tour_stop_id BIGINT REFERENCES tour_stop(id) ON DELETE SET NULL,
    tour_name VARCHAR(255),
    tour_date DATE,
    site_name VARCHAR(255),
    nc_type VARCHAR(32) NOT NULL
        CHECK (nc_type IN ('ECART_QUANTITE','ECART_TEMPERATURE','DELAI_ACHEMINEMENT','COLLECTE_NON_REALISEE','EMBALLAGE','AUTRE')),
    severity VARCHAR(16) NOT NULL CHECK (severity IN ('MINEURE','MAJEURE','CRITIQUE')),
    status VARCHAR(16) NOT NULL CHECK (status IN ('OUVERTE','EN_TRAITEMENT','CLOTUREE')),
    automatic BOOLEAN NOT NULL,
    description VARCHAR(1000) NOT NULL,
    detected_at TIMESTAMP(6) NOT NULL,
    detected_by VARCHAR(255) NOT NULL,
    corrective_action VARCHAR(1000),
    closed_at TIMESTAMP(6),
    closed_by VARCHAR(255)
);
CREATE INDEX idx_nc_company_status ON non_conformity(company_id, status);
CREATE INDEX idx_nc_tour ON non_conformity(tour_id);
